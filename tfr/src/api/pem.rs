//! Minimal PEM reader for the listener certificate and key.
//!
//! The agent reads two files that the installer writes: `identity/agent.cert.pem`
//! and `identity/agent.key.pem` (PKCS#8). A full PEM crate pulls in a base64
//! implementation and a dozen labels; the agent needs exactly one block with an
//! expected label, so the parser here is deliberately single-purpose:
//!
//! * the label must match (a key file fed as a certificate is caught by the label,
//!   not by a confusing DER parse failure);
//! * anything outside the block is ignored, because a real `.pem` may carry
//!   comments and a trailing bag;
//! * the first matching block wins, so a chain file does not accidentally yield
//!   the intermediate certificate as the end entity.

use crate::api::base64;
use crate::error::{Error, Result};

/// Extract the first `-----BEGIN <label>-----` block and decode its body.
pub fn decode_block(text: &str, label: &str) -> Result<Vec<u8>> {
    let begin = format!("-----BEGIN {label}-----");
    let end = format!("-----END {label}-----");
    let start = text
        .find(&begin)
        .ok_or_else(|| Error::Invalid(format!("no {label} block in the PEM file")))?;
    let body_start = start + begin.len();
    let body_end = text[body_start..]
        .find(&end)
        .map(|offset| body_start + offset)
        .ok_or_else(|| Error::Invalid(format!("unterminated {label} block in the PEM file")))?;
    let mut body = String::with_capacity(body_end - body_start);
    for line in text[body_start..body_end].lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with("Proc-Type:") || line.starts_with("DEK-Info:") {
            continue;
        }
        if line.contains(':') {
            return Err(Error::Invalid(
                "PEM headers in the middle of a block are not supported".to_string(),
            ));
        }
        body.push_str(line);
    }
    base64::decode(&body)
}

/// Read a certificate file into DER. Accepts `CERTIFICATE` and, for a chain file,
/// takes the first block, which is by definition the end-entity certificate.
pub fn read_certificate(path: &str) -> Result<Vec<u8>> {
    let text = read_text(path)?;
    decode_block(&text, "CERTIFICATE")
}

/// Read a PKCS#8 private key file into DER.
///
/// PKCS#8 only: `-----BEGIN PRIVATE KEY-----`. The older
/// `-----BEGIN EC PRIVATE KEY-----` / `RSA PRIVATE KEY` forms are rejected with an
/// instruction rather than guessed at, because a wrong guess here means a listener
/// that starts but cannot complete a handshake.
pub fn read_private_key(path: &str) -> Result<Vec<u8>> {
    let text = read_text(path)?;
    if text.contains("-----BEGIN EC PRIVATE KEY-----")
        || text.contains("-----BEGIN RSA PRIVATE KEY-----")
    {
        return Err(Error::Invalid(format!(
            "{path} holds a legacy private key; convert it with \
             `openssl pkcs8 -topk8 -nocrypt -in key.pem -out agent.key.pem`"
        )));
    }
    decode_block(&text, "PRIVATE KEY")
}

fn read_text(path: &str) -> Result<String> {
    std::fs::read_to_string(path).map_err(|error| {
        Error::Io(std::io::Error::new(
            error.kind(),
            format!("cannot read {path}: {error}"),
        ))
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_single_block_decodes() {
        let text = "-----BEGIN TEST-----\nZm9vYmFy\n-----END TEST-----\n";
        assert_eq!(decode_block(text, "TEST").unwrap(), b"foobar");
    }

    #[test]
    fn comments_and_blank_lines_are_ignored() {
        let text = "# generated by the installer\n\n-----BEGIN TEST-----\n\nZm9v\nYmFy\n\
                    -----END TEST-----\n# trailing\n";
        assert_eq!(decode_block(text, "TEST").unwrap(), b"foobar");
    }

    #[test]
    fn a_wrong_label_is_an_error_not_a_silent_empty_der() {
        let text = "-----BEGIN CERTIFICATE-----\nZm9v\n-----END CERTIFICATE-----\n";
        let error = decode_block(text, "PRIVATE KEY").unwrap_err();
        assert!(error.to_string().contains("PRIVATE KEY"));
    }

    #[test]
    fn an_unterminated_block_is_rejected() {
        let text = "-----BEGIN TEST-----\nZm9v\n";
        assert!(decode_block(text, "TEST").is_err());
    }

    #[test]
    fn the_first_block_wins() {
        // A chain file lists the end-entity certificate first; taking the last
        // block would give rustls an intermediate to sign with.
        let text = "-----BEGIN CERTIFICATE-----\nZmlyc3Q=\n-----END CERTIFICATE-----\n\
                    -----BEGIN CERTIFICATE-----\nc2Vjb25k\n-----END CERTIFICATE-----\n";
        assert_eq!(decode_block(text, "CERTIFICATE").unwrap(), b"first");
    }
}
